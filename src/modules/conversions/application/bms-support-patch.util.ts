import type { SupportPatchDataType, SupportPatchRule } from '../domain/support-patch.types';

/** TypeScript type an output field gets for each patch data type. Decimals stay text so no
 * precision is lost to floating point. */
const TS_TYPE: Record<SupportPatchDataType, string> = {
  string: 'string',
  number: 'number',
  integer: 'number',
  BigDecimal: 'string',
  boolean: 'boolean',
  date: 'string',
};

/** Transforms the generated screen can apply when it displays an output field. */
const DISPLAY_TRANSFORMS: Record<string, (expr: string) => string> = {
  trim: (expr) => `String(${expr} ?? '').trim()`,
  toUpperCase: (expr) => `String(${expr} ?? '').toUpperCase()`,
  toLowerCase: (expr) => `String(${expr} ?? '').toLowerCase()`,
};

export interface BmsPatchOutcome {
  content: string;
  applied: string[];
  skipped: { sourceField: string; reason: string }[];
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** bms2react.py names each BMS field's property `field_var(name)`: the field name lower-cased. */
function generatedName(sourceField: string): string {
  return sourceField.trim().toLowerCase();
}

function hasField(content: string, name: string): boolean {
  const n = escapeRegex(name);
  return new RegExp(`\\b(?:formData|receivedData)\\.${n}\\b|^\\s+${n}\\??:`, 'm').test(content);
}

/** Every place bms2react.py writes a field's property name. */
function renameField(content: string, from: string, to: string): string {
  const f = escapeRegex(from);
  return content
    .replace(new RegExp(`\\b(formData|receivedData)\\.${f}\\b`, 'g'), `$1.${to}`)
    .replace(new RegExp(`^(\\s+)${f}(\\??:)`, 'gm'), `$1${to}$2`)
    .replace(new RegExp(`\\b(id|name|htmlFor)="${f}"`, 'g'), `$1="${to}"`)
    .replace(new RegExp(`handleInputChange\\('${f}'`, 'g'), `handleInputChange('${to}'`);
}

/** Sets the declared type of an output field inside `type formOutput = { ... }`. */
function retypeOutputField(content: string, name: string, tsType: string): string {
  return content.replace(/(type formOutput = \{)([\s\S]*?)(\n\})/, (_all, open, body: string, close) => {
    const updated = body.replace(
      new RegExp(`^(\\s+${escapeRegex(name)}\\??:\\s*)[^;]+;`, 'm'),
      `$1${tsType};`,
    );
    return `${open}${updated}${close}`;
  });
}

/** A non-text output field cannot start as '' - its initial value becomes undefined instead. */
function resetOutputInitialValue(content: string, name: string): string {
  return content.replace(
    /(useState<formOutput>\(\{)([\s\S]*?)(\n\s*\}\))/,
    (_all, open: string, body: string, close: string) =>
      `${open}${body.replace(new RegExp(`^(\\s+${escapeRegex(name)}:\\s*)''`, 'm'), '$1undefined')}${close}`,
  );
}

/**
 * Applies support patch rules to a component generated by bms2react.py: renames a BMS field's
 * property to the target name, sets its output type and applies display transforms. A rule
 * that cannot be applied is reported in `skipped`, never silently dropped.
 */
export function applyBmsSupportPatch(tsx: string, rules: SupportPatchRule[]): BmsPatchOutcome {
  let content = tsx;
  const applied: string[] = [];
  const skipped: BmsPatchOutcome['skipped'] = [];

  for (const rule of rules) {
    const from = generatedName(rule.sourceField);
    const to = rule.targetProperty.trim();
    if (!hasField(content, from)) {
      skipped.push({ sourceField: rule.sourceField, reason: 'The field does not exist on this screen' });
      continue;
    }
    if (to !== from && hasField(content, to)) {
      skipped.push({
        sourceField: rule.sourceField,
        reason: `"${to}" is already the name of another field on this screen`,
      });
      continue;
    }

    if (to !== from) content = renameField(content, from, to);
    const tsType = TS_TYPE[rule.dataType];
    content = retypeOutputField(content, to, tsType);
    if (tsType !== 'string') content = resetOutputInitialValue(content, to);

    const transform = rule.transformRule?.trim().replace(/\(\)$/, '');
    let transformApplied = false;
    if (transform) {
      const wrap = DISPLAY_TRANSFORMS[transform];
      const displayed = new RegExp(`\\{receivedData\\.${escapeRegex(to)} \\?\\? ''\\}`, 'g');
      if (!wrap) {
        skipped.push({
          sourceField: rule.sourceField,
          reason: `Transform "${rule.transformRule}" is not supported for screens (only trim, toUpperCase, toLowerCase); the rename and type were applied`,
        });
      } else if (!new RegExp(displayed.source).test(content)) {
        skipped.push({
          sourceField: rule.sourceField,
          reason: `Transform "${rule.transformRule}" applies only to fields the screen displays as plain text; the rename and type were applied`,
        });
      } else {
        content = content.replace(displayed, `{${wrap(`receivedData.${to}`)}}`);
        transformApplied = true;
      }
    }
    applied.push(`${rule.sourceField} -> ${to}: ${rule.dataType}${transformApplied ? ` (${transform})` : ''}`);
  }

  if (applied.length > 0) {
    const header = [
      '// ALSM support patch applied to this generated screen:',
      ...applied.map((line) => `//   ${line}`),
      '',
    ].join('\n');
    content = `${header}${content}`;
  }
  return { content, applied, skipped };
}
